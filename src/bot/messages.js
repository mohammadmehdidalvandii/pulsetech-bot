export function formatStatusMessage(user) {
  const statusMap = {
    active: '🟢 فعال',
    unsubscribed: '🔴 لغو اشتراک‌شده',
    blocked: '⛔ مسدودشده',
  };

  return `📊 <b>وضعیت اشتراک شما در PulseTech</b>

• وضعیت: ${statusMap[user.status] || user.status}
• ایمیل ثبت‌شده: <code>${user.email}</code>
• زمان ارسال روزانه: ساعت ۰۹:۰۰ صبح (به وقت تهران)`;
}